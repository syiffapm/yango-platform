/**
 * Is a line running at this moment? Buses do not drive at 3am, so nothing
 * derived from them — positions, arrivals, "buses on road" — may pretend they
 * do. Lines that finish after midnight are handled by the wrap-around.
 */
export function inServiceHours(route, now = Date.now()) {
  if (!route?.hours) return true
  const [from, to] = route.hours.split('\u2013')
  if (!from || !to) return true
  const mins = (hhmm) => {
    const [h, m] = hhmm.trim().split(':').map(Number)
    return h * 60 + (m || 0)
  }
  const d = new Date(now)
  const cur = d.getHours() * 60 + d.getMinutes()
  const a = mins(from),
    b = mins(to)
  return b >= a ? cur >= a && cur <= b : cur >= a || cur <= b
}

