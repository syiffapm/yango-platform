// Plates are generated so the pool always covers the fleet, however many
// routes the network grows to.
const PLATE_LETTERS = 'ABCDEFGHJKLMNPQRSTUVWXYZ'
function plateFor(i) {
  const region = 1 + Math.floor(i / 26)
  const letter = PLATE_LETTERS[i % PLATE_LETTERS.length]
  const serial = 1000 + ((i * 1117) % 8999)
  return `YGN-${region}${letter}-${serial}`
}

const vehicleClassOf = (routeClass) =>
  routeClass === 'Trunk'
    ? 'City Bus (large)'
    : routeClass === 'Intercity'
      ? 'Express Coach'
      : routeClass === 'Feeder'
        ? 'Midi Bus'
        : 'City Bus'

// A fleet for every licensed operator on every line it holds.
export function buildVehicles(routes) {
  const out = []
  let p = 0
  routes.forEach((r) => {
    const holders = r.operators || [r.operator]
    // Enough vehicles that every licensed operator runs at least two on the line.
    const perOperator = r.class === 'Intercity' ? 2 : 3
    const count = holders.length * perOperator
    for (let i = 0; i < count; i++) {
      const cls = vehicleClassOf(r.class)
      const layout = r.class === 'Intercity' ? (i === 0 ? 'coach-2-2' : 'coach-2-1') : 'urban-40'
      out.push({
        id: `V${String(out.length + 1).padStart(3, '0')}`,
        plate: plateFor(p++),
        chassis: `CHS${90000 + out.length * 137}`,
        operator: holders[i % holders.length],
        route: r.id,
        class: cls,
        seatLayout: layout,
        capacity: seatTemplates[layout].capacity,
        amenities:
          r.class === 'Intercity'
            ? ['AC', 'Wi-Fi', 'Toilet', 'USB', 'Reclining']
            : r.class === 'Trunk'
              ? ['AC', 'Wheelchair', 'CCTV']
              : ['Fan', 'CCTV'],
        imei: `8620${String(45000000 + out.length * 7919)}`,
        dashcam: r.class === 'Trunk',
        apc: r.class === 'Trunk',
        licenceExpiry: ['2026-11-30', '2027-02-14', '2026-10-05', '2027-06-21'][out.length % 4],
        roadworthyExpiry: ['2026-12-12', '2027-01-09', '2026-10-28'][out.length % 3],
        insuranceExpiry: ['2027-03-31', '2026-11-15'][out.length % 2],
        status: out.length === 5 ? 'blocked' : out.length === 12 ? 'maintenance' : 'active',
        odometerKm: 180000 + out.length * 4317,
        photos: [],
      })
    }
  })
  return out
}

