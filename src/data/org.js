export function buildDrivers(vehicles) {
  const out = []
  vehicles.forEach((v, i) => {
    const name = `${mmFirst[i % mmFirst.length]} ${mmLast[(i * 3) % mmLast.length]}`
    out.push({
      id: `D${String(i + 1).padStart(3, '0')}`,
      name,
      nrc: `12/MaGaDa(N)${100000 + i * 731}`,
      phone: `+95 9 7${String(70000000 + i * 131313).slice(0, 8)}`,
      operator: v.operator,
      licenceNo: `DL-${200000 + i * 97}`,
      licenceClass: v.class === 'Express Coach' ? 'E' : 'D',
      licenceExpiry: ['2027-04-30', '2026-10-12', '2027-09-02', '2026-09-30'][i % 4],
      medicalExpiry: i === 3 ? '2026-09-01' : ['2027-01-31', '2026-12-20', '2027-05-15'][i % 3],
      trainingExpiry: '2027-08-01',
      policeClearance: '2026-02-10',
      status: i === 3 ? 'blocked' : i === 9 ? 'pending' : 'active',
      rating: Number((3.4 + ((i * 7) % 16) / 10).toFixed(1)),
      violations: i % 7 === 0 ? 2 : i % 4 === 0 ? 1 : 0,
      hoursThisWeek: 22 + (i % 18),
      vehicle: v.id,
      photo: null,
    })
  })
  return out
}

